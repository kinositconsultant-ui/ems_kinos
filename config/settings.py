def _menu_can_view_my_requests(request):
    """My Requests is employee self-service. Dedicated Staff HR accounts
    (and pure Xefe reviewers) are hidden; multi-group accounts that also hold
    Employess keep access. Superusers keep existing behavior.
    """
    user = getattr(request, "user", None)
    if not getattr(user, "is_authenticated", False):
        return False
    if not user.has_perm("employee_requests.view_employeerequest"):
        return False
    if getattr(user, "is_superuser", False):
        return True
    if user.groups.filter(name="Employess").exists():
        return True
    if user.groups.filter(name__in=["Xefe_Departamentu", "Staff HR"]).exists():
        return False
    return True


def _menu_can_view_leave_calendar(request):
    user = getattr(request, "user", None)
    if not getattr(user, "is_authenticated", False):
        return False
    return bool(getattr(user, "is_superuser", False) or user.has_perm("employee_requests.view_leave_calendar"))



